/** Sentences that carry a number. */
const FR_PATTERNS: ReadonlyArray<readonly [RegExp, (match: RegExpMatchArray) => string]> = [
  [/^The (request body|query parameters|URL parameters|input) is invalid\.$/, () => "Certaines informations sont invalides."],
  [/^Use between (\d+) and (\d+) characters\.$/, (m) => `Utilisez entre ${m[1]} et ${m[2]} caractères.`],
  [/^You can change your username again on (\d{4})-(\d{2})-(\d{2})\.$/, (m) => `Vous pourrez changer de nom d'utilisateur le ${m[3]}/${m[2]}/${m[1]}.`],
  [/^Use at least (\d+) characters\.$/, (m) => `Utilisez au moins ${m[1]} caractères.`],
  [/^Use at most (\d+) characters\.$/, (m) => `Utilisez au plus ${m[1]} caractères.`],
  [/^Keep comments under (\d+) characters\.$/, (m) => `Un commentaire doit faire moins de ${m[1]} caractères.`],
  [/^Keep messages under (\d+) characters\.$/, (m) => `Un message doit faire moins de ${m[1]} caractères.`],
  [/^Attach at most (\d+) images\.$/, (m) => `${m[1]} images maximum.`],
  [/^You must be at least (\d+) years old\.$/, (m) => `Vous devez avoir au moins ${m[1]} ans.`],
  [/^(.+) must be at most (\d+) characters\.$/, (m) => `${m[1]} : ${m[2]} caractères maximum.`],
  [/^(.+) is required\.$/, (m) => `${m[1]} : champ obligatoire.`],
  [/^Keep the prompt under (\d+) characters\.$/, (m) => `La question doit faire moins de ${m[1]} caractères.`],
  [/^The uploaded file exceeds the (\d+) byte limit\.$/, (m) => `Le fichier dépasse la limite de ${Math.round(Number(m[1]) / 1_048_576)} Mo.`],
];

export function localizeServerMessage(message: string, locale: Locale): string {
  if (locale !== "fr") return message;
  const exact = FR[message];
  if (exact) return exact;
  for (const [pattern, render] of FR_PATTERNS) {
    const match = message.match(pattern);
    if (match) return render(match);
  }
  return message;
}
